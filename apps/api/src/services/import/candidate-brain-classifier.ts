  /**
   * Classify a Candidate Fact record.
   */
  public static classifyFact(fact: any): ClassifiedRecord {
    const statement = (fact.statement || '').toLowerCase().trim();
    const factKey = (fact.factKey || '').toLowerCase().trim();

    // Check authentic manual candidate facts
    const authenticFactKeys = new Set([
      'work_authorization',
      'visa_sponsorship',
      'current_location',
      'target_role',
      'education_status',
      'banking_experience',
    ]);

    if (fact.sourceType === 'MANUAL' && authenticFactKeys.has(factKey)) {
      return {
        entityType: 'FACT',
        id: fact.id,
        classification: 'CONFIRMED_AUTHENTIC',
        confidence: 1.0,
        evidence: `Matches baseline candidate fact created during profile initialization (${fact.factKey})`,
        proposedAction: 'RETAIN',
        summary: `[AI:${fact.allowAiUse ? 'YES' : 'NO'}] ${fact.category}: ${(fact.statement || '').slice(0, 50)}...`,
        allowAiUse: fact.allowAiUse,
        verificationStatus: fact.verificationStatus,
        rollbackMethod: 'N/A (Retained)',
      };
    }

    // Check synthetic fixture markers in statement or factKey
    const matchesApex = statement.includes('apex neural dynamics');
    const matchesStanford = statement.includes('stanford university');
    const matchesFintech = statement.includes('global fintech corp');
    const matchesTuBerlin = statement.includes('technical university berlin');
    const matchesMsEngineering = statement.includes('master of science in software engineering');
    const matchesTechSkills = [
      'pytorch',
      'triton',
      'rust',
      'cuda',
      'kubernetes',
      'typescript',
      'node.js',
      'fastify',
      'docker',
      'cloudflare r2',
      'postgresql',
    ].some((s) => statement === `skill: ${s}`);

    if (
      matchesApex ||
      matchesStanford ||
      matchesFintech ||
      matchesTuBerlin ||
      matchesMsEngineering ||
      matchesTechSkills
    ) {
      const isAiAuthorized = fact.allowAiUse === true;
      return {
        entityType: 'FACT',
        id: fact.id,
        classification: 'CONFIRMED_SYNTHETIC',
        confidence: 1.0,
        evidence: `Fact statement references known test fixture content (${statement.slice(0, 60)}) originating from automated test suites (${fact.createdAt})`,
        proposedAction: isAiAuthorized ? 'REVOKE_AI' : 'DELETE',
        summary: `[AI:${fact.allowAiUse ? 'YES' : 'NO'}|${fact.verificationStatus}] ${fact.category}: ${(fact.statement || '').slice(0, 60)}...`,
        allowAiUse: fact.allowAiUse,
        verificationStatus: fact.verificationStatus,
        rollbackMethod: 'Insert record back into candidate_facts with original ID',
      };
    }

    return {
      entityType: 'FACT',
      id: fact.id,
      classification: 'UNDETERMINED',
      confidence: 0.5,
      evidence: 'Candidate fact not matching verified baseline or known test fixtures',
      proposedAction: 'RETAIN',
      summary: `[AI:${fact.allowAiUse ? 'YES' : 'NO'}] ${fact.category}: ${(fact.statement || '').slice(0, 50)}...`,
      allowAiUse: fact.allowAiUse,
      verificationStatus: fact.verificationStatus,
      rollbackMethod: 'N/A (Retained)',
    };
  }

