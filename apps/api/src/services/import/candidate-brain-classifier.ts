/**
 * Candidate Brain Record-Level Classification Engine
 *
 * Implements strict, evidence-based classification for candidate records:
 * - CONFIRMED_SYNTHETIC: Proven synthetic origin via known test fixture markers, test document filenames, or test session timestamps.
 * - CONFIRMED_AUTHENTIC: Directly verified against Master CV (Resume - Asadbek M.pdf) and verified candidate baseline.
 * - POSSIBLY_SYNTHETIC: Suspicious records requiring explicit human review.
 * - UNDETERMINED: Records with insufficient provenance evidence to determine authenticity.
 *
 * Prime Directive: Never delete or mutate records without conclusive record-level provenance.
 */

export type RecordClassification =
  'CONFIRMED_SYNTHETIC' | 'CONFIRMED_AUTHENTIC' | 'POSSIBLY_SYNTHETIC' | 'UNDETERMINED';

export type ProposedAction = 'DELETE' | 'RETAIN' | 'UPDATE_PROFILE' | 'REVOKE_AI';

export interface ClassifiedRecord {
  entityType:
    | 'PROFILE'
    | 'EXPERIENCE'
    | 'EDUCATION'
    | 'SKILL'
    | 'CERTIFICATION'
    | 'LANGUAGE'
    | 'LINK'
    | 'FACT'
    | 'DOCUMENT'
    | 'SESSION'
    | 'ITEM';
  id: string;
  classification: RecordClassification;
  confidence: number;
  evidence: string;
  proposedAction: ProposedAction;
  summary: string;
  allowAiUse?: boolean;
  verificationStatus?: string;
  rollbackMethod: string;
}

