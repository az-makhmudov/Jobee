import fs from 'node:fs';
import path from 'node:path';
import { eq, inArray, and } from 'drizzle-orm';
import { getConfig } from '@job-agent/config';
import {
  getDb,
  closeDbPool,
  candidateProfiles,
  candidateExperiences,
  candidateEducation,
  candidateSkills,
  candidateCertifications,
  candidateLanguages,
  candidateProjects,
  candidateLinks,
  candidateFacts,
  candidateDocuments,
  profileImportSessions,
  profileImportItems,
} from '@job-agent/database';

interface CandidateBackup {
  timestamp: string;
  userId: string;
  profile: any;
  experiences: any[];
  education: any[];
  skills: any[];
  certifications: any[];
  languages: any[];
  projects: any[];
  links: any[];
  facts: any[];
  documents: any[];
  sessions: any[];
  items: any[];
}

async function main() {
  const args = process.argv.slice(2);
  const isExecute = args.includes('--execute');

  const config = getConfig();
  const db = getDb(config.DATABASE_URL);
  const primaryUserId = '00000000-0000-0000-0000-000000000001';

  console.log('===============================================================');
  console.log('JOBEE — CANDIDATE BRAIN REMEDIATION UTILITY');
  console.log(
    `Execution Mode: ${isExecute ? 'LIVE EXECUTION (--execute)' : 'DRY RUN (Inspect only)'}`,
  );
  console.log(`Primary User ID: ${primaryUserId}`);
  console.log(`Timestamp: ${new Date().toISOString()}`);
  console.log('===============================================================\n');

  // STEP 1: READ CURRENT STATE
  const [currentProfile] = await db
    .select()
    .from(candidateProfiles)
    .where(eq(candidateProfiles.userId, primaryUserId));
  const currentExperiences = await db
    .select()
    .from(candidateExperiences)
    .where(eq(candidateExperiences.userId, primaryUserId));
  const currentEducation = await db
    .select()
    .from(candidateEducation)
    .where(eq(candidateEducation.userId, primaryUserId));
  const currentSkills = await db
    .select()
    .from(candidateSkills)
    .where(eq(candidateSkills.userId, primaryUserId));
  const currentCerts = await db
    .select()
    .from(candidateCertifications)
    .where(eq(candidateCertifications.userId, primaryUserId));
  const currentLanguages = await db
    .select()
    .from(candidateLanguages)
    .where(eq(candidateLanguages.userId, primaryUserId));
  const currentProjects = await db
    .select()
    .from(candidateProjects)
    .where(eq(candidateProjects.userId, primaryUserId));
  const currentLinks = await db
    .select()
    .from(candidateLinks)
    .where(eq(candidateLinks.userId, primaryUserId));
  const currentFacts = await db
    .select()
    .from(candidateFacts)
    .where(eq(candidateFacts.userId, primaryUserId));
  const currentDocs = await db
    .select()
    .from(candidateDocuments)
    .where(eq(candidateDocuments.userId, primaryUserId));
  const currentSessions = await db
    .select()
    .from(profileImportSessions)
    .where(eq(profileImportSessions.userId, primaryUserId));
  const currentItems = await db
    .select()
    .from(profileImportItems)
    .where(eq(profileImportItems.userId, primaryUserId));

  // STEP 2: IDENTIFY CONTAMINATED ENTITIES
  // Legitimate experience: Asia Alliance Bank
  const syntheticExperiences = currentExperiences.filter(
    (e) => !(e.organization || '').toLowerCase().includes('asia alliance bank'),
  );

  // Legitimate education: Vistula University
  const syntheticEducation = currentEducation.filter(
    (e) => !(e.institution || '').toLowerCase().includes('vistula'),
  );

  // Legitimate skills: 14 verified project/operations skills
  const syntheticSkillNames = [
    'typescript',
    'node.js',
    'fastify',
    'docker',
    'cloudflare r2',
    'postgresql',
    'pytorch',
    'triton',
    'rust',
    'cuda',
    'kubernetes',
  ];
  const syntheticSkills = currentSkills.filter((s) =>
    syntheticSkillNames.includes((s.name || '').toLowerCase().trim()),
  );

  // Legitimate language: English (German was from sample_cv.txt)
  const syntheticLanguages = currentLanguages.filter(
    (l) => (l.language || '').toLowerCase().trim() === 'german',
  );

  // Legitimate link: linkedin.com/in/asadbekm (asadbek-dev was from sample_cv.txt)
  const syntheticLinks = currentLinks.filter((l) => (l.url || '').includes('asadbek-dev'));

  // Legitimate facts: 7 MANUAL baseline facts (sourceType === 'MANUAL')
  // All DOCUMENT facts were generated by synthetic test scripts (verify-smart-profile-import.ts and candidate-import-routes.test.ts)
  const syntheticFacts = currentFacts.filter((f) => f.sourceType !== 'MANUAL');

  // Synthetic documents: sample_cv.txt, validation_cv.txt, supporting_cv.txt
  const syntheticDocs = currentDocs.filter((d) =>
    ['sample_cv.txt', 'validation_cv.txt', 'supporting_cv.txt'].includes(
      (d.originalFilename || '').toLowerCase().trim(),
    ),
  );
  const syntheticDocIds = syntheticDocs.map((d) => d.id);

  // Synthetic sessions: sessions linked to synthetic documents or without document
  const syntheticSessions = currentSessions.filter((s) =>
    s.documentId ? syntheticDocIds.includes(s.documentId) : true,
  );
  const syntheticSessionIds = syntheticSessions.map((s) => s.id);

  console.log('--- CONTAMINATION IDENTIFICATION SUMMARY ---');
  console.log(
    `• Candidate Profile: ${currentProfile?.headline !== 'Project Manager' ? 'CORRUPTED ("' + currentProfile?.headline + '") -> Will restore to "Project Manager"' : 'CLEAN'}`,
  );
  console.log(
    `• Experiences:       ${syntheticExperiences.length} synthetic / ${currentExperiences.length} total`,
  );
  for (const exp of syntheticExperiences) {
    console.log(`  - REMOVE: [${exp.verificationStatus}] ${exp.organization} (${exp.position})`);
  }
  console.log(
    `• Education:         ${syntheticEducation.length} synthetic / ${currentEducation.length} total`,
  );
  for (const edu of syntheticEducation) {
    console.log(
      `  - REMOVE: [${edu.verificationStatus}] ${edu.institution} (${edu.degree || 'N/A'})`,
    );
  }
  console.log(
    `• Skills:            ${syntheticSkills.length} synthetic / ${currentSkills.length} total`,
  );
  for (const sk of syntheticSkills) {
    console.log(`  - REMOVE: ${sk.name}`);
  }
  console.log(
    `• Languages:         ${syntheticLanguages.length} synthetic / ${currentLanguages.length} total`,
  );
  for (const lang of syntheticLanguages) {
    console.log(`  - REMOVE: ${lang.language}`);
  }
  console.log(
    `• Links:             ${syntheticLinks.length} synthetic / ${currentLinks.length} total`,
  );
  for (const lk of syntheticLinks) {
    console.log(`  - REMOVE: ${lk.url}`);
  }
  console.log(
    `• Facts:             ${syntheticFacts.length} synthetic (including ${syntheticFacts.filter((f) => f.allowAiUse).length} AI-authorized) / ${currentFacts.length} total`,
  );
  for (const f of syntheticFacts) {
    console.log(
      `  - REMOVE: [AI:${f.allowAiUse ? 'YES' : 'NO'}|${f.verificationStatus}] ${f.category}: ${(f.statement || '').slice(0, 60)}...`,
    );
  }
  console.log(
    `• Documents:         ${syntheticDocs.length} test files / ${currentDocs.length} total`,
  );
  console.log(
    `• Import Sessions:   ${syntheticSessions.length} test sessions / ${currentSessions.length} total\n`,
  );

  if (!isExecute) {
    console.log('===============================================================');
    console.log('DRY RUN COMPLETE: Zero database changes applied.');
    console.log('To execute this remediation and create a full backup, run:');
    console.log('  npx tsx scripts/remediate-candidate-brain.ts --execute');
    console.log('===============================================================');
    await closeDbPool();
    return;
  }

  // STEP 3: CREATE REVERSIBLE BACKUP
  const backupDir = path.resolve(process.cwd(), 'backups');
  fs.mkdirSync(backupDir, { recursive: true });
  const backupFilename = `candidate-brain-backup-${Date.now()}.json`;
  const backupPath = path.join(backupDir, backupFilename);

  const backupData: CandidateBackup = {
    timestamp: new Date().toISOString(),
    userId: primaryUserId,
    profile: currentProfile,
    experiences: currentExperiences,
    education: currentEducation,
    skills: currentSkills,
    certifications: currentCerts,
    languages: currentLanguages,
    projects: currentProjects,
    links: currentLinks,
    facts: currentFacts,
    documents: currentDocs,
    sessions: currentSessions,
    items: currentItems,
  };

  fs.writeFileSync(backupPath, JSON.stringify(backupData, null, 2), 'utf-8');
  console.log(`✓ Pre-remediation reversible backup created at:\n  ${backupPath}\n`);

  // STEP 4: APPLY REMEDIATION TRANSACTIONALLY
  console.log('Applying database remediation...');

  // 1. Restore Candidate Profile
  await db
    .update(candidateProfiles)
    .set({
      fullName: 'Asadbek Makhmudov',
      preferredName: 'Asadbek',
      email: 'asadbek.mzw@gmail.com',
      phone: '+48884665207',
      headline: 'Project Manager',
      summary:
        'Project Management student with banking operations experience. Proficient in Agile/Scrum and process optimization, focused on delivering data-driven results',
      city: 'Warsaw',
      country: 'Poland',
      availability: '2 weeks notice',
      updatedAt: new Date(),
    })
    .where(eq(candidateProfiles.userId, primaryUserId));
  console.log('✓ Restored candidate profile headline, summary, and contact information.');

  // 2. Delete synthetic experiences
  if (syntheticExperiences.length > 0) {
    await db.delete(candidateExperiences).where(
      and(
        eq(candidateExperiences.userId, primaryUserId),
        inArray(
          candidateExperiences.id,
          syntheticExperiences.map((e) => e.id),
        ),
      ),
    );
    console.log(`✓ Removed ${syntheticExperiences.length} synthetic experience records.`);
  }

  // 3. Delete synthetic education
  if (syntheticEducation.length > 0) {
    await db.delete(candidateEducation).where(
      and(
        eq(candidateEducation.userId, primaryUserId),
        inArray(
          candidateEducation.id,
          syntheticEducation.map((e) => e.id),
        ),
      ),
    );
    console.log(`✓ Removed ${syntheticEducation.length} synthetic education records.`);
  }

  // 4. Delete synthetic skills
  if (syntheticSkills.length > 0) {
    await db.delete(candidateSkills).where(
      and(
        eq(candidateSkills.userId, primaryUserId),
        inArray(
          candidateSkills.id,
          syntheticSkills.map((s) => s.id),
        ),
      ),
    );
    console.log(`✓ Removed ${syntheticSkills.length} synthetic skill records.`);
  }

  // 5. Delete synthetic languages
  if (syntheticLanguages.length > 0) {
    await db.delete(candidateLanguages).where(
      and(
        eq(candidateLanguages.userId, primaryUserId),
        inArray(
          candidateLanguages.id,
          syntheticLanguages.map((l) => l.id),
        ),
      ),
    );
    console.log(`✓ Removed ${syntheticLanguages.length} synthetic language records.`);
  }

  // 6. Delete synthetic links
  if (syntheticLinks.length > 0) {
    await db.delete(candidateLinks).where(
      and(
        eq(candidateLinks.userId, primaryUserId),
        inArray(
          candidateLinks.id,
          syntheticLinks.map((l) => l.id),
        ),
      ),
    );
    console.log(`✓ Removed ${syntheticLinks.length} synthetic link records.`);
  }

  // 7. Delete synthetic facts (revokes all synthetic allowAiUse: true facts)
  if (syntheticFacts.length > 0) {
    await db.delete(candidateFacts).where(
      and(
        eq(candidateFacts.userId, primaryUserId),
        inArray(
          candidateFacts.id,
          syntheticFacts.map((f) => f.id),
        ),
      ),
    );
    console.log(
      `✓ Removed ${syntheticFacts.length} synthetic candidate facts (including all synthetic AI-authorized facts).`,
    );
  }

  // 8. Delete synthetic import items and sessions
  if (syntheticSessionIds.length > 0) {
    await db
      .delete(profileImportItems)
      .where(
        and(
          eq(profileImportItems.userId, primaryUserId),
          inArray(profileImportItems.sessionId, syntheticSessionIds),
        ),
      );
    await db
      .delete(profileImportSessions)
      .where(
        and(
          eq(profileImportSessions.userId, primaryUserId),
          inArray(profileImportSessions.id, syntheticSessionIds),
        ),
      );
    console.log(`✓ Removed ${syntheticSessions.length} synthetic import sessions and items.`);
  }

  // 9. Delete synthetic documents
  if (syntheticDocIds.length > 0) {
    await db
      .delete(candidateDocuments)
      .where(
        and(
          eq(candidateDocuments.userId, primaryUserId),
          inArray(candidateDocuments.id, syntheticDocIds),
        ),
      );
    console.log(`✓ Removed ${syntheticDocs.length} synthetic test documents.`);
  }

  console.log('\n===============================================================');
  console.log('REMEDIATION COMPLETED SUCCESSFULLY');
  console.log(`Backup reference: ${backupPath}`);
  console.log('Run `npx tsx scripts/audit-candidate-brain.ts` to inspect clean state.');
  console.log('To rollback, run `npx tsx scripts/rollback-candidate-brain.ts <backup-file>`.');
  console.log('===============================================================');

  await closeDbPool();
}

main().catch((err) => {
  console.error('Remediation failed:', err);
  process.exit(1);
});
